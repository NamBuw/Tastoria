"""Generate backend/.importlinter from docs/sad/model.yaml (modules[].deps), ADR 0001.

    uv run --package tastoria-backend python backend/scripts/gen_importlinter.py          # write
    uv run --package tastoria-backend python backend/scripts/gen_importlinter.py --check  # CI: fail if stale

Only modules that exist as packages get contracts; adding a module package makes the check fail until the file
is regenerated, so the contracts always cover every module in the code.

Contracts per module X:
  * forbidden  — X does not import a module outside deps(X) (direct imports; going through an allowed module's
                 service is fine), nor the assembly modules (tastoria.app, .cli, .models_registry, .migrations);
  * protected  — X's internals (everything but service.py and schemas.py) are imported only from inside X or by
                 the assembly modules;
and one acyclic_siblings contract over tastoria.modules.
"""

from __future__ import annotations

import sys
from pathlib import Path

import yaml

BACKEND = Path(__file__).resolve().parents[1]
REPO = BACKEND.parent
SRC = BACKEND / "src" / "tastoria"
MODEL = REPO / "docs" / "sad" / "model.yaml"
OUT = BACKEND / ".importlinter"
PUBLIC = {"service", "schemas", "__init__"}
ASSEMBLY = ["tastoria.app", "tastoria.cli", "tastoria.models_registry", "tastoria.migrations"]
TOP_LEVEL = {"core", "jobs"}  # packages directly under tastoria/; the others live in tastoria/modules/


def package(name: str) -> str:
    return f"tastoria.{name}" if name in TOP_LEVEL else f"tastoria.modules.{name}"


def package_dir(name: str) -> Path:
    return SRC / name if name in TOP_LEVEL else SRC / "modules" / name


def internals(name: str) -> list[str]:
    d = package_dir(name)
    subs = sorted(p.stem for p in d.glob("*.py") if p.stem not in PUBLIC)
    subs += sorted(p.name for p in d.iterdir() if p.is_dir() and (p / "__init__.py").exists())
    if name == "core":  # core is shared infrastructure; only its table mapping is private
        subs = [s for s in subs if s == "models"]
    return [f"{package(name)}.{s}" for s in subs]


def render() -> str:
    modules = yaml.safe_load(MODEL.read_text(encoding="utf-8"))["modules"]
    present = [m for m in modules if (package_dir(m["name"]) / "__init__.py").exists()]
    names = [m["name"] for m in present]
    out = [
        "# GENERATED by backend/scripts/gen_importlinter.py from docs/sad/model.yaml — do not edit by hand.",
        "# Run: uv run --package tastoria-backend lint-imports --config backend/.importlinter",
        f"# Modules with code: {', '.join(names)}",
        "",
        "[importlinter]",
        "root_package = tastoria",
        "include_external_packages = False",
        "",
    ]
    for m in present:
        name, deps = m["name"], set(m.get("deps") or [])
        forbidden = [package(o) for o in names if o != name and o not in deps] + ASSEMBLY
        out += [
            f"[importlinter:contract:{m['id']}-{name}-deps]",
            f"name = {m['id']} {name} may import only {', '.join(sorted(deps)) or 'no other module'} (model.yaml)",
            "type = forbidden",
            f"source_modules = {package(name)}",
            "forbidden_modules =",
            *[f"    {f}" for f in forbidden],
            "allow_indirect_imports = True",
            "",
        ]
        private = internals(name)
        if private:
            allowed = [package(name), "tastoria.app", "tastoria.cli", "tastoria.models_registry"]
            scope = "models" if name == "core" else "all but service, schemas"
            out += [
                f"[importlinter:contract:{m['id']}-{name}-private]",
                f"name = {m['id']} {name}: internals are private ({scope})",
                "type = protected",
                "protected_modules =",
                *[f"    {p}" for p in private],
                "allowed_importers =",
                *[f"    {a}" for a in allowed],
                "",
            ]
    out += [
        "[importlinter:contract:modules-acyclic]",
        "name = no import cycles between business modules",
        "type = acyclic_siblings",
        "ancestors = tastoria.modules",
        "",
    ]
    return "\n".join(out)


def main() -> int:
    text = render()
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            print(f"{OUT} is stale; run backend/scripts/gen_importlinter.py", file=sys.stderr)
            return 1
        return 0
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
