#!/usr/bin/env python3
"""Sinh từ điển dữ liệu docs/sad/05-tu-dien-du-lieu.md từ catalog của một CSDL PostgreSQL đang chạy.

CSDL phải đã áp db/schema.sql. Script đọc catalog qua `docker exec <container> psql -At`, nhóm bảng
theo module trong docs/sad/model.yaml, và ghi mỗi bảng một mục: mô tả (COMMENT ON TABLE) rồi bảng
Cột | Kiểu | NULL | Mặc định | Ràng buộc | Phân loại | Ý nghĩa, kèm ràng buộc nhiều cột (có chú thích), chỉ mục,
trigger, thời hạn lưu/xoá, quy mô ước lượng và luật chỉ kiểm ở service. Phân loại dữ liệu, thời hạn lưu và luật
service lấy từ db/dictionary_meta.py (catalog không chứa các thông tin này). Không sửa tay tệp sinh ra; sửa COMMENT
trong db/schema.sql hoặc db/dictionary_meta.py rồi chạy lại.

Dùng:
    uv run --with pyyaml python db/gen_dictionary.py --container <tên container> [--db tastoria] \
        [--user postgres] [--out docs/sad/05-tu-dien-du-lieu.md]
"""
from __future__ import annotations

import argparse
import pathlib
import subprocess
import sys

import yaml

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import dictionary_meta as meta  # noqa: E402

ROOT = pathlib.Path(__file__).resolve().parents[1]
FS, RS = "\x1f", "\x1e"


class Catalog:
    def __init__(self, container: str, db: str, user: str):
        self.base = ["docker", "exec", container, "psql", "-U", user, "-d", db, "-X", "-At",
                     "-v", "ON_ERROR_STOP=1", "-F", FS, "-R", RS, "-c"]

    def q(self, sql: str) -> list[list[str]]:
        r = subprocess.run(self.base + [sql], capture_output=True, text=True)
        if r.returncode != 0:
            sys.exit(f"psql lỗi: {r.stderr.strip()}")
        recs = (rec.strip("\n") for rec in r.stdout.split(RS))
        return [rec.split(FS) for rec in recs if rec]


def cell(s: str | None) -> str:
    if s is None or s == "":
        return ""
    return s.replace("\\", "\\\\").replace("|", "\\|").replace("\n", " ")


def code(s: str) -> str:
    return f"`{s}`" if s else ""


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--container", required=True)
    ap.add_argument("--db", default="tastoria")
    ap.add_argument("--user", default="postgres")
    ap.add_argument("--model", default=str(ROOT / "docs/sad/model.yaml"))
    ap.add_argument("--out", default=str(ROOT / "docs/sad/05-tu-dien-du-lieu.md"))
    a = ap.parse_args()

    model = yaml.safe_load(pathlib.Path(a.model).read_text(encoding="utf-8"))
    cat = Catalog(a.container, a.db, a.user)

    cols = cat.q("""
        SELECT c.relname, a.attnum::text, a.attname, format_type(a.atttypid, a.atttypmod),
               CASE WHEN a.attnotnull THEN 'NOT NULL' ELSE 'NULL' END,
               COALESCE(pg_get_expr(d.adbin, d.adrelid), ''),
               CASE a.attidentity WHEN 'a' THEN 'GENERATED ALWAYS AS IDENTITY'
                                  WHEN 'd' THEN 'GENERATED BY DEFAULT AS IDENTITY' ELSE '' END,
               COALESCE(col_description(c.oid, a.attnum), ''), c.relkind::text
          FROM pg_class c
          JOIN pg_namespace n ON n.oid = c.relnamespace AND n.nspname = 'public'
          JOIN pg_attribute a ON a.attrelid = c.oid AND a.attnum > 0 AND NOT a.attisdropped
          LEFT JOIN pg_attrdef d ON d.adrelid = c.oid AND d.adnum = a.attnum
         WHERE c.relkind IN ('r', 'v')
         ORDER BY c.relname, a.attnum""")
    tdesc = dict(cat.q("""
        SELECT c.relname, COALESCE(obj_description(c.oid, 'pg_class'), '')
          FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace AND n.nspname = 'public'
         WHERE c.relkind IN ('r', 'v')"""))
    cons = cat.q("""
        SELECT k.conrelid::regclass::text, k.conname, k.contype::text,
               (SELECT string_agg(a.attname, ',' ORDER BY array_position(k.conkey, a.attnum))
                  FROM pg_attribute a WHERE a.attrelid = k.conrelid AND a.attnum = ANY (k.conkey)),
               pg_get_constraintdef(k.oid),
               COALESCE(k.confrelid::regclass::text, ''),
               COALESCE(obj_description(k.oid, 'pg_constraint'), ''),
               COALESCE((SELECT string_agg(a.attname, ',' ORDER BY array_position(k.confkey, a.attnum))
                           FROM pg_attribute a WHERE a.attrelid = k.confrelid AND a.attnum = ANY (k.confkey)), ''),
               k.confdeltype::text
          FROM pg_constraint k
         WHERE k.connamespace = 'public'::regnamespace AND k.contype IN ('p', 'u', 'f', 'c')
         ORDER BY 1, k.contype, k.conname""")
    idx = cat.q("""
        SELECT i.tablename, i.indexname, i.indexdef,
               COALESCE(obj_description(format('%I', i.indexname)::regclass, 'pg_class'), '')
          FROM pg_indexes i
         WHERE i.schemaname = 'public'
           AND NOT EXISTS (SELECT 1 FROM pg_constraint k WHERE k.conname = i.indexname
                             AND k.connamespace = 'public'::regnamespace)
         ORDER BY 1, 2""")
    enums = cat.q("""
        SELECT t.typname, string_agg(e.enumlabel, ', ' ORDER BY e.enumsortorder)
          FROM pg_type t JOIN pg_enum e ON e.enumtypid = t.oid
          JOIN pg_namespace n ON n.oid = t.typnamespace AND n.nspname = 'public'
         GROUP BY t.typname ORDER BY t.typname""")
    trigs = cat.q("""
        SELECT t.tgrelid::regclass::text, t.tgname, pg_get_triggerdef(t.oid),
               COALESCE(obj_description(t.oid, 'pg_trigger'), '')
          FROM pg_trigger t
          JOIN pg_class c ON c.oid = t.tgrelid
          JOIN pg_namespace n ON n.oid = c.relnamespace AND n.nspname = 'public'
         WHERE NOT t.tgisinternal
         ORDER BY 1, 2""")
    exts = cat.q("SELECT extname, extversion FROM pg_extension WHERE extname <> 'plpgsql' ORDER BY 1")
    server = cat.q("SHOW server_version")[0][0]

    by_rel: dict[str, list[list[str]]] = {}
    kinds: dict[str, str] = {}
    for r in cols:
        by_rel.setdefault(r[0], []).append(r)
        kinds[r[0]] = r[8]
    col_cons: dict[tuple[str, str], list[str]] = {}
    tbl_cons: dict[str, list[str]] = {}
    ondel = {"c": " ON DELETE CASCADE", "n": " ON DELETE SET NULL", "r": " ON DELETE RESTRICT",
             "d": " ON DELETE SET DEFAULT", "a": ""}
    counts = {"p": 0, "u": 0, "f": 0, "c": 0}
    for rel, name, typ, keys, defn, ftab, ccom, fkeys, fdel in cons:
        counts[typ] += 1
        ks = keys.split(",") if keys else []
        if typ == "p":
            label = "PK" if len(ks) == 1 else f"PK ({', '.join(ks)})"
        elif typ == "u":
            label = "UNIQUE" if len(ks) == 1 else defn
        elif typ == "f":
            label = f"FK → {ftab}({fkeys.replace(',', ', ')}){ondel.get(fdel, '')}"
            if len(ks) > 1:
                label = f"FK ({', '.join(ks)}) → {ftab}({fkeys.replace(',', ', ')}){ondel.get(fdel, '')}"
        else:
            label = defn
        if typ in ("u", "c") and len(ks) > 1 or (typ == "f" and len(ks) > 1 and ccom):
            tbl_cons.setdefault(rel, []).append(f"`{name}`: `{defn}`" + (f" — {ccom}" if ccom else ""))
            if typ != "f":
                continue
        elif ccom:
            tbl_cons.setdefault(rel, []).append(f"`{name}`: `{defn}` — {ccom}")
        for k in ks:
            col_cons.setdefault((rel, k), []).append(label)
    idx_by: dict[str, list[tuple[str, str, str]]] = {}
    for t, n, d, c in idx:
        idx_by.setdefault(t, []).append((n, d, c))
    trg_by: dict[str, list[tuple[str, str, str]]] = {}
    for t, n, d, c in trigs:
        trg_by.setdefault(t, []).append((n, d, c))

    tables = model["tables"]
    views = model.get("views", [])
    missing = [t["name"] for t in tables if t["name"] not in by_rel]
    extra = sorted(set(k for k, v in kinds.items() if v == "r") - {t["name"] for t in tables})
    if missing or extra:
        sys.exit(f"Catalog lệch model.yaml: thiếu {missing}, thừa {extra}")

    out: list[str] = []
    w = out.append
    ncol = sum(len(by_rel[t["name"]]) for t in tables)
    w("# Từ điển dữ liệu Tastoria\n")
    w("> Tệp sinh tự động bởi `db/gen_dictionary.py` từ catalog PostgreSQL sau khi áp `db/schema.sql`. "
      "Không sửa tay: sửa `COMMENT ON` hoặc DDL trong `db/schema.sql`, hoặc phân loại, thời hạn lưu, "
      "luật service trong `db/dictionary_meta.py`, rồi chạy lại script.\n")
    w(f"- Máy chủ: PostgreSQL {server}; extension: "
      + ", ".join(f"{e} {v}" for e, v in exts) + ".")
    n_partial = sum(1 for _, _, d, _ in idx if " WHERE " in d)
    w(f"- Quy mô: {len(tables)} bảng, {ncol} cột, {len(views)} view, {len(enums)} kiểu liệt kê; "
      f"{counts['p']} khoá chính, {counts['f']} khoá ngoại, {counts['u']} ràng buộc UNIQUE, "
      f"{counts['c']} ràng buộc CHECK, {len(idx)} chỉ mục bổ sung (trong đó {n_partial} chỉ mục một phần), "
      f"{len(trigs)} trigger.")
    w("- Cột **NULL**: `NOT NULL` là bắt buộc; `NULL` là được phép trống. Cột **Ràng buộc** ghi PK, UNIQUE, FK "
      "(kèm hành động ON DELETE; không ghi là NO ACTION) và CHECK một cột; ràng buộc nhiều cột ghi dưới bảng.")
    w("- Cột **Phân loại** theo NĐ 356/2025: " + "; ".join(f"{v}" for v in meta.CLASS_LABEL.values())
      + ". Định nghĩa ở `db/dictionary_meta.py`; thời hạn lưu theo `07-danh-gia-tac-dong-du-lieu-ca-nhan.md` mục 9.")
    w("- Cột `numeric` không khai precision/scale: đơn vị và miền ghi ở cột Ý nghĩa và ở CHECK. Quy mô ước lượng "
      "là giả định thiết kế cho bản thử 1.000 người dùng trong 1 năm, kho 200 món; dùng để chọn chỉ mục, không phải số đo.")
    w("- Nhóm bảng theo module của modular monolith (`docs/sad/model.yaml`). Ghi chú thiết kế lấy từ trường "
      "`notes` của mô hình.\n")

    w("## Mục lục\n")
    mods = [m for m in model["modules"] if any(t["module"] == m["name"] for t in tables)
            or any(v["module"] == m["name"] for v in views)]
    for m in mods:
        names = [t["name"] for t in tables if t["module"] == m["name"]]
        vnames = [v["name"] for v in views if v["module"] == m["name"]]
        w(f"- **{m['id']} {m['name']}**: " + ", ".join(f"`{n}`" for n in names + vnames))
    w("")

    w("## Ánh xạ máy trạng thái sang lược đồ\n")
    w("Máy trạng thái trong `model.yaml` có một số trạng thái không là giá trị của cột enum nào:\n")
    w("| Thực thể | Cách biểu diễn trong CSDL |\n|---|---|")
    for ent, how in meta.STATE_MAPPING:
        w(f"| {ent} | {cell(how)} |")
    w("")

    w("## Kiểu liệt kê\n")
    w("| Kiểu | Giá trị |\n|---|---|")
    for n, vals in enums:
        w(f"| `{n}` | {cell(vals)} |")
    w("")

    def table_md(rel: str, is_view: bool) -> None:
        if is_view:
            w("| Cột | Kiểu | Ý nghĩa |")
            w("|---|---|---|")
        else:
            w("| Cột | Kiểu | NULL | Mặc định | Ràng buộc | Phân loại | Ý nghĩa |")
            w("|---|---|---|---|---|---|---|")
        default_cls = meta.TABLES.get(rel, ("KCN",))[0]
        for r in by_rel[rel]:
            _, _, cname, typ, nn, dflt, ident, desc, _ = r
            if is_view:
                w(f"| `{cname}` | `{cell(typ)}` | {cell(desc)} |")
                continue
            d = ident or dflt
            cc = "; ".join(col_cons.get((rel, cname), []))
            cls = meta.COLUMNS.get((rel, cname), default_cls)
            w(f"| `{cname}` | `{cell(typ)}` | {nn} | {code(cell(d))} | "
              f"{code(cell(cc)) if cc else ''} | {meta.CLASS_LABEL[cls]} | {cell(desc)} |")
        w("")

    for m in mods:
        w(f"## {m['id']} — module `{m['name']}`\n")
        w(f"{m['desc']}.\n")
        for t in [t for t in tables if t["module"] == m["name"]]:
            rel = t["name"]
            w(f"### `{rel}`\n")
            w(f"{tdesc.get(rel, '')}\n")
            table_md(rel, False)
            extras = tbl_cons.get(rel, [])
            if extras:
                w("Ràng buộc nhiều cột hoặc có chú thích:\n")
                for e in extras:
                    w(f"- {e.replace('|', chr(92) + '|')}")
                w("")
            if idx_by.get(rel):
                w("Chỉ mục:\n")
                for n, d, c in idx_by[rel]:
                    w(f"- `{n}`: `{'UNIQUE ' if d.startswith('CREATE UNIQUE') else ''}{d.split(' USING ', 1)[1]}`"
                      + (f" — {c}" if c else ""))
                w("")
            if trg_by.get(rel):
                w("Trigger:\n")
                for n, d, c in trg_by[rel]:
                    when = d.split(" ON ", 1)[0].split(n, 1)[1].strip()
                    fn = d.split("EXECUTE FUNCTION ", 1)[1]
                    w(f"- `{n}` ({when.lower()}): `{fn}`" + (f" — {c}" if c else ""))
                w("")
            tm = meta.TABLES.get(rel)
            if tm is None:
                sys.exit(f"Thiếu {rel} trong db/dictionary_meta.py")
            w(f"Lưu/Xoá: {tm[1]}. Quy mô ước lượng: {tm[2]}.\n")
            if tm[3]:
                w(f"Ràng buộc chỉ kiểm ở service: {tm[3]}\n")
            if t.get("notes"):
                w(f"Ghi chú thiết kế: {t['notes']}.\n")
        for v in [v for v in views if v["module"] == m["name"]]:
            rel = v["name"]
            if rel not in by_rel:
                sys.exit(f"Thiếu view {rel} trong catalog")
            w(f"### View `{rel}`\n")
            w(f"{tdesc.get(rel, '')}\n")
            table_md(rel, True)

    pathlib.Path(a.out).write_text("\n".join(out).rstrip() + "\n", encoding="utf-8")
    print(f"đã ghi {a.out}: {len(tables)} bảng, {ncol} cột, {len(views)} view")


if __name__ == "__main__":
    main()
